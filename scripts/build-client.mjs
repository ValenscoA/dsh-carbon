/**
 * Build `lib/client.js` from `src/client/`.
 *
 * The shell serves plugin bundles as plain scripts that call
 * `window.__ModuleLoader__.load({ id, factory })`, where the factory is
 * CommonJS: `require` is the shared module table (React and friends), and the
 * returned exports become the plugin body. esbuild gives us the CJS body; this
 * script supplies the wrapper the module system expects.
 *
 * React stays external on purpose: bundling a second copy would break hooks and
 * context. Everything else (the page, icons, copy) is bundled so the package
 * ships one self-contained file.
 */
import { build } from 'esbuild';
import { mkdir, writeFile } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const ENTRY = join(ROOT, 'src', 'client', 'index.jsx');
const OUTPUT = join(ROOT, 'lib', 'client.js');
const PACKAGE_ID = 'dsh-carbon';

const result = await build({
  entryPoints: [ENTRY],
  bundle: true,
  write: false,
  format: 'cjs',
  platform: 'browser',
  target: ['es2022'],
  jsx: 'automatic',
  external: ['react', 'react-dom', 'react/jsx-runtime'],
  loader: { '.css': 'text' },
  minify: false,
  legalComments: 'none',
  logLevel: 'silent',
});

const body = result.outputFiles[0].text;
const wrapper = `/**
 * dsh-carbon browser bundle. Generated by scripts/build-client.mjs from
 * src/client/ \u2014 edit the source, run \`npm run build:client\`, commit this file.
 */
window.__ModuleLoader__.load({
  id: ${JSON.stringify(PACKAGE_ID)},
  factory: (require) => {
    var module = { exports: {} };
    var exports = module.exports;
${body}
    return module.exports;
  }
});
`;

await mkdir(dirname(OUTPUT), { recursive: true });
await writeFile(OUTPUT, wrapper, 'utf8');

console.log(`built ${OUTPUT} (${Buffer.byteLength(wrapper)} bytes)`);
